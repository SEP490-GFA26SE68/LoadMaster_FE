import {expect,test} from './fixtures'
import {dispatcherListResponse} from '../src/test/dispatcher-list-fixture'
async function open(page:import('@playwright/test').Page,path='/yeu-cau-giao'){
 const calls:URL[]=[]
 await page.route('**/*',r=>['localhost','127.0.0.1'].includes(new URL(r.request().url()).hostname)?r.fallback():r.abort())
 await page.route('**/src/lib/backend-config.ts*',r=>r.fulfill({contentType:'application/javascript',
  body:"export const BACKEND_FEATURES=['trips','fleet'];export const backendConfig={authSource:'mock',apiUrl:location.origin,features:new Set(['trips','fleet']),keycloak:{url:'',realm:'',clientId:''}};export const usesBackend=name=>backendConfig.features.has(name);export const resolveBackendConfig=()=>backendConfig;"}))
 await page.route(/\/api\//,async r=>{
  expect(r.request().method()).toBe('GET')
  const u=new URL(r.request().url());calls.push(u)
  return u.searchParams.get('search')==='ERR'?r.fulfill({status:403,json:{success:false,code:'FORBIDDEN'}}):r.fulfill({json:dispatcherListResponse(u)})
 })
 await page.route(/\/(yeu-cau-giao|chuyen)(\?|$)/,async r=>{
  if(r.request().resourceType()!=='document')return r.fallback()
  const response=await r.fetch({url:new URL('/',r.request().url()).href,headers:{'if-none-match':'','if-modified-since':''}})
  return r.fulfill({response,status:200,body:(await response.text()).replace('/src/main.tsx','/src/test/browser/dispatcher-lists-harness.tsx')})
 })
 await page.goto(path)
 return calls
}
test('Requirements tripCode target beyond page one; multi-filter, total and reload',async({page,browserErrors},info)=>{
 const calls=await open(page,'/yeu-cau-giao?trang=3')
 await expect(page.getByRole('button',{name:'Xem chi tiết yêu cầu 51',exact:true})).toBeVisible()
 await page.getByRole('searchbox').fill('TRIP-TARGET')
 await expect(page.getByRole('button',{name:'Xem chi tiết yêu cầu 109',exact:true})).toBeVisible()
 await expect(page.getByText('1–2 / 2',{exact:true})).toBeVisible()
 expect(calls.at(-1)?.searchParams.get('page')).toBe('0')
 await page.goto('/yeu-cau-giao?q=TRIP-TARGET&trang-thai=giao-thieu&uu-tien=cao&han-tu=2026-11-12&han-den=2026-11-12')
 await expect(page.getByText('1–2 / 2',{exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByText('1–2 / 2',{exact:true})).toBeVisible()
 await page.screenshot({path:info.outputPath('requirements-combined.png')})
 expect(browserErrors).toEqual([])
})
