import {expect,test} from './fixtures'
import {fleetListResponse} from '../src/test/fleet-list-fixture'
async function open(page:import('@playwright/test').Page,path='/doi-xe'){
 const calls:URL[]=[]
 await page.route('**/*',r=>['localhost','127.0.0.1'].includes(new URL(r.request().url()).hostname)?r.fallback():r.abort())
 await page.route(/\/api\//,async r=>{
  expect(r.request().method()).toBe('GET')
  const u=new URL(r.request().url());calls.push(u)
  return u.searchParams.get('search')==='ERR'?r.fulfill({status:403,json:{success:false,code:'FORBIDDEN'}}):r.fulfill({json:fleetListResponse(u)})
 })
 await page.route('**/doi-xe*',async r=>{
  if(r.request().resourceType()!=='document')return r.fallback()
  const response=await r.fetch({url:new URL('/',r.request().url()).href})
  return r.fulfill({response,body:(await response.text()).replace('/src/main.tsx','/src/test/browser/fleet-list-harness.tsx')})
 })
 await page.goto(path)
 await expect(page.getByRole('searchbox')).toBeVisible()
 return calls
}
test('Dispatcher Fleet filters maintenance from later page and combines type/search',async({page,browserErrors},info)=>{
 const calls=await open(page,'/doi-xe?trang=4')
 await expect(page.getByRole('link',{name:'Vehicle 076',exact:true})).toBeVisible()
 await page.getByRole('combobox',{name:'Trạng thái',exact:true}).click()
 await page.getByRole('option',{name:'Bảo dưỡng',exact:true}).click()
 await expect(page.getByText('1–2 / 2',{exact:true})).toBeVisible()
 expect(calls.at(-1)?.searchParams.get('page')).toBe('0')
 expect(calls.at(-1)?.searchParams.get('status')).toBe('MAINTENANCE')
 await page.goto('/doi-xe?q=PLATE-07&trang-thai=bao-duong&loai-xe=2')
 await expect(page.getByText('1–1 / 1',{exact:true})).toBeVisible()
 await expect(page.getByRole('link',{name:'Vehicle 076',exact:true})).toBeVisible()
 await expect(page.getByRole('link',{name:'Vehicle 077',exact:true})).toHaveCount(0)
 await page.reload()
 await expect(page.getByText('1–1 / 1',{exact:true})).toBeVisible()
 await page.screenshot({path:info.outputPath('fleet-combined.png')})
 expect(browserErrors).toEqual([])
})
test('Fleet sorts globally ASC/DESC and page2 keeps filtered total',async({page,browserErrors},info)=>{
 const calls=await open(page)
 await expect(page.getByRole('link',{name:'Same name',exact:true})).toHaveCount(2)
 await page.getByRole('button',{name:'Phương tiện',exact:true}).click()
 await expect(page.getByRole('link',{name:'Vehicle 100',exact:true})).toBeVisible()
 expect(calls.at(-1)?.searchParams.get('sortDir')).toBe('DESC')
 await page.getByRole('button',{name:'Trang sau',exact:true}).click()
 await expect(page.getByRole('link',{name:'Vehicle 074',exact:true})).toBeVisible()
 await expect(page.getByText('26–50 / 100',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Phương tiện',exact:true}).click()
 await expect(page.getByRole('link',{name:'Same name',exact:true})).toHaveCount(2)
 await expect(page.getByText('1–25 / 100',{exact:true})).toBeVisible()
 expect(calls.at(-1)?.searchParams.get('sortDir')).toBe('ASC')
 await page.screenshot({path:info.outputPath('fleet-sort.png')})
 expect(browserErrors).toEqual([])
})
test('Fleet search preserves URL on reload and distinguishes empty from error',async({page,browserErrors},info)=>{
 await open(page)
 await page.getByRole('searchbox').fill('PLATE-090')
 await expect(page.getByRole('link',{name:'Target truck',exact:true})).toBeVisible()
 await expect(page.getByText('1–1 / 1',{exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByRole('link',{name:'Target truck',exact:true})).toBeVisible()
 await page.getByRole('searchbox').fill('not-present')
 await expect(page.locator('tbody tr')).toHaveCount(1)
 await expect(page.getByRole('link',{name:'Target truck',exact:true})).toHaveCount(0)
 await page.getByRole('searchbox').fill('ERR')
 await expect(page.getByText('Không tải được đội xe',{exact:true})).toBeVisible()
 await expect(page.getByRole('table')).toHaveCount(0)
 await page.screenshot({path:info.outputPath('fleet-error.png')})
 expect(browserErrors).toEqual([])
})
