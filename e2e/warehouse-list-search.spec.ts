import {expect,test} from './fixtures'
import {warehouseListResponse,warehousePackages} from '../src/test/package-list-fixture'
async function open(page:import('@playwright/test').Page,path:string){
 const calls:URL[]=[]
 await page.route('**/*',r=>['localhost','127.0.0.1'].includes(new URL(r.request().url()).hostname)?r.fallback():r.abort())
 await page.route(/\/api\//,async r=>{
  expect(r.request().method()).toBe('GET')
  const u=new URL(r.request().url());calls.push(u)
  if(u.searchParams.get('search')==='ERR')return r.fulfill({status:403,json:{success:false,code:'FORBIDDEN'}})
  const id=/^\/api\/packages\/(\d+)$/.exec(u.pathname)?.[1]
  return r.fulfill({json:id?{success:true,data:warehousePackages.find(p=>p.id===Number(id))}:warehouseListResponse(u)})
 })
 for(const route of ['**/kien-hang*','**/loai-kien*'])await page.route(route,async r=>{
  if(r.request().resourceType()!=='document')return r.fallback()
  const response=await r.fetch({url:new URL('/',r.request().url()).href})
  return r.fulfill({response,body:(await response.text()).replace('/src/main.tsx','/src/test/browser/warehouse-lists-harness.tsx')})
 })
 await page.goto(path)
 await expect(page.getByRole('searchbox')).toBeVisible()
 return calls
}
const code=(page:import('@playwright/test').Page,value:string)=>page.getByRole('button',{name:value,exact:true})
test('Warehouse Packages searches full fixture, combines filters and opens correct detail',async({page,browserErrors},info)=>{
 const calls=await open(page,'/kien-hang?trang=6')
 await expect(code(page,'PKG-126')).toBeVisible()
 await page.getByRole('searchbox').fill('PKG-126')
 await expect(page.getByText('1–1 / 1',{exact:true})).toBeVisible()
 expect(calls.at(-1)?.searchParams.get('page')).toBe('0')
 await code(page,'PKG-126').click()
 await expect(page.getByRole('complementary')).toBeVisible()
 expect(calls.some(u=>u.pathname==='/api/packages/126')).toBe(true)
 await page.goto('/kien-hang?q=PKG-1&trang-thai=hoan-tra&loai-hang=de-vo')
 await expect(code(page,'PKG-102')).toBeVisible()
 await expect(page.getByText('1–17 / 17',{exact:true})).toBeVisible()
 expect(calls.at(-1)?.searchParams.get('status')).toBe('RETURNED')
 expect(calls.at(-1)?.searchParams.get('handlingClass')).toBe('FRAGILE')
 await page.reload()
 await expect(code(page,'PKG-102')).toBeVisible()
 await page.screenshot({path:info.outputPath('packages-combined.png')})
 expect(browserErrors).toEqual([])
})
